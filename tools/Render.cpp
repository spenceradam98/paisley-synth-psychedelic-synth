#include <juce_audio_utils/juce_audio_utils.h>
#include "../Source/PluginProcessor.h"
#include "../Source/PluginEditor.h"

// Usage: PaisleyRender <outDir>
int main (int argc, char** argv)
{
    juce::ScopedJuceInitialiser_GUI gui;
    juce::File out (argc > 1 ? juce::String (argv[1]) : juce::File::getCurrentWorkingDirectory().getFullPathName());
    const bool calibrate = argc > 2 && juce::String (argv[2]) == "--calibrate";
    juce::String levels;
    out.createDirectory();
    const double sr = 48000.0; const int block = 256;

    PaisleyProcessor proc;
    proc.setPlayConfigDetails (0, 2, sr, block);
    auto& pm = proc.presets;
    int problems = 0;
    juce::String report;

    for (int p = 0; p < pm.getEntries().size(); ++p)
    {
        const auto e = pm.getEntries()[p];
        pm.load (p);
        if (calibrate) proc.apvts.getParameter ("master")->setValueNotifyingHost (proc.apvts.getParameter ("master")->convertTo0to1 (0.25f));
        proc.prepareToPlay (sr, block);
        const int total = (int) (sr * 6.0);
        juce::AudioBuffer<float> all (2, total);
        all.clear();
        const bool mono = proc.apvts.getRawParameterValue ("voiceMode")->load() > 0.5f;
        // poly: a chord (C3 E3 G3 B3) held 2.5s; mono: a little phrase
        const int notes[] = { 48, 52, 55, 59 };
        for (int pos = 0; pos < total; pos += block)
        {
            const int n = juce::jmin (block, total - pos);
            juce::AudioBuffer<float> buf (2, n);
            juce::MidiBuffer midi;
            auto at = [&] (double sec) { int s = (int) (sec * sr); return s >= pos && s < pos + n ? s - pos : -1; };
            if (mono)
            {
                const int phrase[] = { 48, 55, 60, 58, 55 };
                for (int k = 0; k < 5; ++k)
                {
                    if (int t = at (k * 0.5); t >= 0) midi.addEvent (juce::MidiMessage::noteOn (1, phrase[k], 0.8f), t);
                    if (int t = at (k * 0.5 + 0.45); t >= 0) midi.addEvent (juce::MidiMessage::noteOff (1, phrase[k]), t);
                }
            }
            else
                for (int nn : notes)
                {
                    if (int t = at (0.0); t >= 0) midi.addEvent (juce::MidiMessage::noteOn (1, nn, 0.8f), t);
                    if (int t = at (2.5); t >= 0) midi.addEvent (juce::MidiMessage::noteOff (1, nn), t);
                }
            proc.processBlock (buf, midi);
            for (int c = 0; c < 2; ++c) all.copyFrom (c, pos, buf, c, 0, n);
        }
        float peak = all.getMagnitude (0, total);
        float rms = (all.getRMSLevel (0, 0, (int) (sr * 2.5)) + all.getRMSLevel (1, 0, (int) (sr * 2.5))) * 0.5f;
        if (calibrate)
        {
            const float target = juce::Decibels::decibelsToGain (mono ? -13.0f : -15.0f);
            const float m = juce::jlimit (0.05f, 2.0f, juce::jmin (0.25f * target / juce::jmax (rms, 1e-4f), 0.25f * 0.8f / juce::jmax (peak, 1e-4f)));
            levels << "    { \"" << e.name << "\", " << juce::String (m, 3) << "f },\n";
        }
        bool nan = false;
        for (int c = 0; c < 2; ++c) for (int i = 0; i < total; ++i) if (! std::isfinite (all.getSample (c, i))) nan = true;
        juce::String flag;
        if (nan) flag << " NAN";
        if (rms < 0.01f) flag << " QUIET";
        if (peak > 0.97f) flag << " HOT";
        if (flag.isNotEmpty()) ++problems;
        report << juce::String (p).paddedLeft ('0', 2) << " " << e.category.paddedRight (' ', 10) << e.name.paddedRight (' ', 24)
               << " peak " << juce::String (peak, 3) << " rms " << juce::String (juce::Decibels::gainToDecibels (rms), 1) << " dB" << flag << "\n";

        auto file = out.getChildFile ("audio").getChildFile (e.category + " - " + e.name + ".wav");
        file.getParentDirectory().createDirectory(); file.deleteFile();
        juce::WavAudioFormat wav;
        if (auto os = file.createOutputStream())
            if (auto w = std::unique_ptr<juce::AudioFormatWriter> (wav.createWriterFor (os.get(), sr, 2, 16, {}, 0)))
            { os.release(); w->writeFromAudioSampleBuffer (all, 0, total); }
    }
    std::cout << report << "presets with problems: " << problems << std::endl;
    if (calibrate)
    {
        juce::File (juce::String (argv[3])).replaceWithText ("// Generated by PaisleyRender --calibrate: per-preset master level for even loudness.\n#pragma once\n#include <map>\n#include <string>\ninline const std::map<std::string, float> factoryPresetLevels {\n" + levels + "};\n");
        return 0;
    }

    // Editor snapshots, one per theme
    pm.load (0);
    std::unique_ptr<juce::AudioProcessorEditor> ed (proc.createEditor());
    ed->setSize (PaisleyEditor::designW, PaisleyEditor::designH);
    for (int t = 0; t < (int) getThemes().size(); ++t)
    {
        if (auto* pe = dynamic_cast<PaisleyEditor*> (ed.get()))
        {
            proc.setThemeIndex (t);
            // re-create to apply theme from processor
            ed.reset (proc.createEditor());
            ed->setSize (PaisleyEditor::designW, PaisleyEditor::designH);
        }
        auto img = ed->createComponentSnapshot (ed->getLocalBounds(), true, 1.0f);
        auto f = out.getChildFile ("theme-" + juce::String (t + 1) + "-" + juce::File::createLegalFileName (getThemes()[(size_t) t].name).replace (" ", "-") + ".png");
        f.deleteFile();
        juce::PNGImageFormat png;
        if (auto os = f.createOutputStream()) png.writeImageToStream (img, *os);
    }
    ed.reset();
    proc.setThemeIndex (0);
    return problems == 0 ? 0 : 1;
}
